# Arithmetic operators
# +   add
# -   subtract
# *   multiply
# /   divide (always gives a float)
# %   remainder
# **  power
# //  floor divide (drops the decimal)

print(7 + 2)    # 9
print(7 - 2)    # 5
print(7 * 2)    # 14
print(7 / 2)    # 3.5
print(7 % 2)    # 1
print(7 ** 2)   # 49
print(7 // 2)   # 3
