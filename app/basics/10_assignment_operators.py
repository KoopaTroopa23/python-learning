# Assignment operators
# =    assign
# +=   add and assign
# -=   subtract and assign
# *=   multiply and assign
# /=   divide and assign
# %=   remainder and assign
# **=  power and assign
# //=  floor divide and assign

count = 10
count += 5   # same as count = count + 5
print(count)  # 15
count *= 2
print(count)  # 30
