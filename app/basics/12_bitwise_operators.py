# Bitwise:
# &   = bitwise AND
# |   = bitwise OR
# ^   = bitwise XOR
# ~   = bitwise NOT
# <<  = left shift
# >>  = right shift

print(5 & 3)    # 1  (0101 & 0011 = 0001)
print(5 | 3)    # 7  (0101 | 0011 = 0111)
print(5 ^ 3)    # 6  (0101 ^ 0011 = 0110)
print(~5)       # -6
print(5 << 1)   # 10
print(5 >> 1)   # 2
